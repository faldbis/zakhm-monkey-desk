#!/usr/bin/env python3
"""Backtest the user's ZAKHM OSMA strategy on one real UTC day and render the Monkey Desk reel.
   python3 run_day.py --date 2026-10-16 --day 8 --start 431.25 [--lev 20 --margin-pct 0.10 --line-mode body]"""
import argparse, json, os, subprocess, sys, csv
import pandas as pd
D = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(D, "strategy"))
from zakhm_backtest import simulate, SYMS

ONES = "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen".split()
TENS = "_ _ twenty thirty forty fifty sixty seventy eighty ninety".split()
def words(n): return ONES[n] if n < 20 else TENS[n // 10] + ("" if n % 10 == 0 else "-" + ONES[n % 10])

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", required=True); ap.add_argument("--day", type=int, required=True); ap.add_argument("--start", type=float, required=True)
    ap.add_argument("--lev", type=float, default=20); ap.add_argument("--margin-pct", type=float, default=0.10)
    ap.add_argument("--fee", type=float, default=0.0005); ap.add_argument("--slip", type=float, default=0.0002)
    ap.add_argument("--line-mode", default="body", choices=["body", "wick"])
    ap.add_argument("--tag", default="", help="suffix for the data file, e.g. road")
    ap.add_argument("--label", default="", help="menu label on the web page")
    ap.add_argument("--out"); ap.add_argument("--render", action="store_true", help="also render an MP4 (optional)"); ap.add_argument("--no-vo", action="store_true")
    a = ap.parse_args()
    r = simulate(a.date, a.start, a.lev, a.margin_pct, a.fee, a.slip, line_mode=a.line_mode)
    d0 = pd.Timestamp(a.date, tz="UTC"); mins = lambda t: round((t - d0) / pd.Timedelta(minutes=1), 2)
    short = lambda s: s.replace("USDT", "")
    trades = [dict(sym=short(t["sym"]), side=t["side"], lev=int(t["lev"]), entry=t["entry"], exit=t["exit"], pct=round(t["roe"], 1),
                   pnl=round(t["pnl"], 2), o=mins(t["entry_time"]), c=mins(t["exit_time"]), margin=round(t["margin"], 2), fees=round(t["fees"], 2),
                   reason=t["reason"], tf=t["tf"], sl=t["sl"], tp=t["tp"], zone=t["zone"]) for t in r["trades"]]
    candles = {}
    for s, df in r["data"].items():
        candles[short(s)] = dict(t0=mins(df.index[0]), o=[round(x, 6) for x in df.open], h=[round(x, 6) for x in df.high],
                                 l=[round(x, 6) for x in df.low], c=[round(x, 6) for x in df.close])
    events = [[mins(e["time"]), short(e["sym"]), e["kind"], e["tf"], e["side"], e["lvl"]] for e in r["events"]]
    end = r["start"] + sum(t["pnl"] for t in trades)
    vo = f"audio/vo_day{a.day}.mp3"
    cfg = dict(day=a.day, dateLabel=f"{d0:%A} {d0.day} {d0:%b}", dateISO=a.date, startBalance=a.start, endBalance=round(end, 2),
               wins=sum(t["pnl"] > 0 for t in trades), losses=sum(t["pnl"] <= 0 for t in trades), leverage=int(a.lev),
               feesTotal=round(sum(t["fees"] for t in trades), 2), strategyName="ZAKHM OSMA", startMinute=0, timeline=[[0, 0], [1, 1440]],
               chartSym=(events[-1][1] if events else "ETH"), voiceover=vo, trades=trades, candles=candles, events=events)
    name = f"day_{a.date}" + (f"_{a.tag}" if a.tag else "")
    os.makedirs(os.path.join(D, "data"), exist_ok=True)
    js = os.path.join(D, "data", f"{name}.js")
    open(js, "w").write("// generated by run_day.py — real Binance candles + ZAKHM OSMA backtest\nwindow.DAY_CONFIG=" + json.dumps(cfg) + ";\n")
    with open(os.path.join(D, "data", f"{name}_trades.csv"), "w", newline="") as f:
        w = csv.writer(f); w.writerow(["#", "sym", "side", "tf", "entry_utc", "exit_utc", "entry", "sl", "tp", "exit", "reason", "margin", "roe_%", "pnl_$", "fees_$"])
        for i, t in enumerate(r["trades"], 1):
            w.writerow([i, t["sym"], t["side"], t["tf"], t["entry_time"], t["exit_time"], t["entry"], t["sl"], t["tp"], t["exit"], t["reason"], round(t["margin"], 2), round(t["roe"], 2), round(t["pnl"], 2), round(t["fees"], 2)])
    summary = dict(date=a.date, day=a.day, start=a.start, end=round(end, 2), pct=round((end / a.start - 1) * 100, 2), trades=len(trades),
                   wins=cfg["wins"], losses=cfg["losses"], skipped=[dict(time=str(s["time"]), sym=s["sym"], side=s["side"], reason=s["reason"]) for s in r["skipped"]],
                   events_in_day=len(events), params=r["params"])
    json.dump(summary, open(os.path.join(D, "data", f"{name}_summary.json"), "w"), indent=1)
    print(json.dumps(summary, indent=1))
    for t in trades: print(t)
    # menu index for the web page
    idx_fn = os.path.join(D, "data", "index.json")
    idx = json.load(open(idx_fn)) if os.path.exists(idx_fn) else []
    idx = [x for x in idx if x["file"] != f"data/{name}.js"]
    idx.append(dict(file=f"data/{name}.js", date=a.date, day=a.day, start=a.start, end=round(end, 2), trades=len(trades),
                    label=a.label or f"{a.date} · Day {a.day} · ${a.start:.2f} → ${end:.2f} · {len(trades)} trades"))
    idx.sort(key=lambda x: (x["file"]))
    json.dump(idx, open(idx_fn, "w"), indent=1)
    open(os.path.join(D, "data", "index.js"), "w").write("window.DAYS=" + json.dumps(idx) + ";\n")
    if not a.no_vo:
        if not os.path.exists(os.path.join(D, vo)):
            subprocess.run([os.path.join(D, "make_vo.sh"), str(a.day), words(a.day)], check=True)
    if a.render:
        out = a.out or os.path.join(D, f"zakhm_day{a.day}_{a.date}.mp4")
        subprocess.run([sys.executable, os.path.join(D, "render.py"), out, os.path.join(D, vo), f"data/{name}.js"], check=True)

if __name__ == "__main__": main()
